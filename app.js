function setLanguage(lang) {
  const dict = I18N[lang];
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(node => {
    const value = dict[node.dataset.i18n];
    if (typeof value === "string") node.textContent = value;
  });
  document.querySelectorAll(".langs button").forEach(button => {
    button.classList.toggle("active", button.dataset.lang === lang);
    button.setAttribute("aria-pressed", button.dataset.lang === lang);
  });
  renderDynamic(dict);
  // After a language switch show re-rendered blocks at once, no replayed animation or blank gaps.
  if (revealObserver) document.querySelectorAll(".reveal").forEach(node => node.classList.add("in"));
  observeReveal();
  try { localStorage.setItem(STORAGE_KEY, lang); } catch (error) { /* storage blocked */ }
}

let revealObserver;
function observeReveal() {
  if (!("IntersectionObserver" in window)) {
    document.querySelectorAll(".reveal").forEach(node => node.classList.add("in"));
    return;
  }
  revealObserver ||= new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("in");
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -40px 0px" });
  document.querySelectorAll(".reveal:not(.in)").forEach(node => revealObserver.observe(node));
}

document.querySelectorAll(".langs button").forEach(button => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

